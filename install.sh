#!/usr/bin/env bash
# Link every skill in ./skills into ~/.agents/skills (Codex and other agents)
# and ~/.claude/skills (Claude Code). Safe to re-run after every `git pull`.
#
# Per-machine opt-outs: list skill names, one per line, in
#   ~/.config/agent-skills/skip
# Skipped skills are unlinked on that machine.
#
# Anything already sitting at a link's path that isn't one of our links is
# moved to ~/.agents/backups/<timestamp>/ instead of being deleted.
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
agents="$HOME/.agents/skills"
claude="$HOME/.claude/skills"
skip_file="${XDG_CONFIG_HOME:-$HOME/.config}/agent-skills/skip"
backup="$HOME/.agents/backups/$(date +%Y%m%d-%H%M%S)"

mkdir -p "$agents" "$claude"

skipped() { [[ -f "$skip_file" ]] && grep -qxF "$1" "$skip_file"; }

stash() {
  mkdir -p "$backup/$2"
  mv "$1" "$backup/$2/"
  echo "  moved $1 -> $backup/$2/"
}

# link <target> <path> <label>
link() {
  local target="$1" path="$2" label="$3"
  if [[ -L "$path" && "$(readlink "$path")" == "$target" ]]; then return; fi
  if [[ -e "$path" || -L "$path" ]]; then stash "$path" "$label"; fi
  ln -s "$target" "$path"
  echo "  linked $path"
}

while IFS= read -r skill_file; do
  dir="$(dirname "$skill_file")"
  name="$(basename "$dir")"
  if skipped "$name"; then
    for p in "$claude/$name" "$agents/$name"; do
      [[ -L "$p" ]] && rm "$p" && echo "  unlinked $p (skipped)"
    done
    continue
  fi
  link "$dir" "$agents/$name" agents
  link "../../.agents/skills/$name" "$claude/$name" claude
done < <(find "$repo/skills" -mindepth 2 -name SKILL.md -print | sort)

# Remove links to skills that were deleted from the repo.
for p in "$agents"/* "$claude"/*; do
  [[ -L "$p" && ! -e "$p" ]] && rm "$p" && echo "  pruned $p"
done

# Shared agent instructions and Claude Code config. ~/.claude/CLAUDE.md links to
# ~/.agents/AGENTS.md; ~/.codex/AGENTS.md is generated below.
mkdir -p "$HOME/.codex" "$HOME/.claude/rules" "$HOME/.claude/agents"
link "$repo/config/AGENTS.md" "$HOME/.agents/AGENTS.md" config
link "../.agents/AGENTS.md" "$HOME/.claude/CLAUDE.md" config
link "$repo/config/repos.md" "$HOME/.agents/repos.md" config

# Codex reads one file, so ~/.codex/AGENTS.md is generated: the shared
# instructions plus the Codex-only ones. Re-run install.sh after editing either.
codex_md="$HOME/.codex/AGENTS.md"
[[ -L "$codex_md" ]] && rm "$codex_md"
{
  echo "<!-- Generated by ~/DEV/github/skills/install.sh from config/AGENTS.md + config/codex/AGENTS.md. Edit those, not this. -->"
  cat "$repo/config/AGENTS.md"
  echo
  sed '1,/^## /{/^## /!d;}' "$repo/config/codex/AGENTS.md"
} > "$codex_md.tmp" && mv "$codex_md.tmp" "$codex_md"
echo "  wrote $codex_md"

# Claude Code settings: merge the shared keys from config/claude/settings.json
# into ~/.claude/settings.json. Keys not in the shared file (hooks, statusLine,
# autoMode, anything a tool installed) are left alone. Skipped in CI.
if [[ -z "${CI:-}" ]] && command -v python3 >/dev/null; then
  python3 -I - "$repo/config/claude/settings.json" "$HOME/.claude/settings.json" <<'PY'
import json, os, sys
shared_path, target = sys.argv[1], sys.argv[2]
shared = json.load(open(shared_path))
current = json.load(open(target)) if os.path.exists(target) else {}
merged = {**current, **shared}
if merged != current:
    tmp = target + ".tmp"
    with open(tmp, "w") as f:
        json.dump(merged, f, indent=2)
        f.write("\n")
    os.replace(tmp, target)
    print(f"  merged shared settings into {target}")
PY
fi
for f in "$repo"/config/claude/rules/*.md "$repo"/config/claude/agents/*.md; do
  sub="$(basename "$(dirname "$f")")"
  link "$f" "$HOME/.claude/$sub/$(basename "$f")" config
done
# Codex custom agents (sol_engineer, sol_researcher, sol_reviewer).
mkdir -p "$HOME/.codex/agents"
for f in "$repo"/config/codex/agents/*.toml; do
  link "$f" "$HOME/.codex/agents/$(basename "$f")" config
done

echo "done: $(find "$repo/skills" -mindepth 2 -name SKILL.md | wc -l | tr -d ' ') skills in repo"
